# NESTA AULA FORAM APRESENTADOS OS OPERADORES MATEMÁTICOS EM RUBY

# ADIÇÃO -> REPRESENTADO PELO SINAL DE MAIS (+)

a = 10 + 10

# SUBTRAÇÃO -> REPRESENTADO PELO SINAL DE MENOS (-)

b = 10 - 5

# MULTIPLICAÇÃO -> REPRESENTADO PELO SINAL DE ASTERISCO (*)

c = 10 * 5

# DIVISÃO -> REPRESENTADO PELO SINAL DE BARRA (/)

d = 10 / 2

# MÓDULO -> REPRESENTADO PELO SINAL DE PORCENTAGEM (%)

e = 10 % 3

# EXPONENCIAÇÃO -> REPRESENTADO PELO SINAL DE ASTERISCO DUPLO (**)

f = 2 ** 3