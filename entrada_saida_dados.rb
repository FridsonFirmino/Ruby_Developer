# NESTA AULA FORAM APRESENTADOS OS MÉTODOS DE ENTRADA E SAÍDA DE DADOS EM RUBY

# ENTRADA DE DADOS 

# O MÉTODO gets -> CAPTURA DADOS DO USUÁRIO
# O MÉTODO chomp -> REMOVE A QUEBRA DE LINHA DO FINAL DA STRING

nome = gets.chomp

# PARA CONVERTER UMA STRING EM UM NÚMERO INTEIRO, UTILIZAMOS O MÉTODO to_i

idade = gets.chomp.to_i

# PARA CONVERTER UMA STRING EM UM NÚMERO DE PONTO FLUTUANTE, UTILIZAMOS O MÉTODO to_f

altura = gets.chomp.to_f

# PARA CONVERTER UMA STRING EM UM NÚMERO BOOLEANO, UTILIZAMOS O MÉTODO to_b

ativo = gets.chomp.to_b


# SAÍDA DE DADOS -> MÉTODO puts OU print

puts "Olá, #{nome}!"
print "Olá, #{nome}!"
