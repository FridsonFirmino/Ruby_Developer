# NESTA AULA FORAM APRESENTADOS OS TIPOS DE DADOS EM RUBY


# INTEIRO

a = 10

# FLOAT

b = 10.5 

# BOOLEANO

c = true 
d = false

# NIL

# EM RUBY, O NULO É REPRESENTADO PELO OBJETO NIL, QUE É UM OBJETO ESPECIAL QUE REPRESENTA A AUSÊNCIA DE VALOR.

# SYMBOL

# EM RUBY, UM SYMBOL É UMA INSTÂNCIA DA CLASSE SYMBOL, QUE É UM OBJETO IMUTÁVEL QUE REPRESENTA UM NOME ÚNICO.
# OS SYMBOLS SÃO MUITO UTILIZADOS COMO CHAVES EM HASHES E PARA REPRESENTAR NOMES DE MÉTODOS.
i = :nome

# STRING

e = "Oi, eu sou uma string"

# ARRAY

# EM RUBY, UM ARRAY É UMA COLEÇÃO DE ELEMENTOS, QUE PODEM SER DE QUALQUER TIPO DE DADO.
f = [1,2,3,4,5]

# HASH

# EM RUBY, UM HASH É UMA COLEÇÃO DE PARES CHAVE-VALOR.
# ESTE HASH PODE SER ESCRITO DE DUAS FORMAS DIFERENTES, MAS O RESULTADO É O MESMO.


g = { "nome" => "fridson", "idade" => 30, "cidade" => "Luanda" }
h = { nome: "fridson", idade: 30, cidade: "Luanda" }

# FORMAS DE ACEDER AOS ELEMENTOS DE UM HASH

puts g["nome"]
puts h[:nome]